
import streamlit as st
import pandas as pd
import joblib

# ================================
# PAGE CONFIGURATION
# ================================

st.set_page_config(
    page_title="CardioAI",
    page_icon="🫀",
    layout="centered"
)

# ================================
# LOAD MODEL
# ================================

model = joblib.load("CardioAI.pkl")

# ================================
# HEADER / BRANDING
# ================================

st.title("CardioAI")

st.subheader(
    "AI-Based Heart Disease Risk Prediction and Analysis System"
)

st.write(
    "CardioAI uses a machine learning model to analyze "
    "patient health parameters and estimate the presence "
    "of heart disease."
)

st.warning(
    "This application is intended for educational and "
    "research purposes only. It is not a medical diagnosis "
    "or a substitute for professional medical advice."
)

# ================================
# PATIENT INFORMATION
# ================================

st.header("Patient Information")

age = st.number_input(
    "Age",
    min_value=1,
    max_value=120,
    value=50
)

sex = st.selectbox(
    "Sex",
    [0, 1],
    format_func=lambda x: "Female" if x == 0 else "Male"
)

chest_pain = st.selectbox(
    "Chest Pain Type",
    [1, 2, 3, 4]
)

bp = st.number_input(
    "Blood Pressure (BP)",
    min_value=50,
    max_value=250,
    value=120
)

cholesterol = st.number_input(
    "Cholesterol",
    min_value=50,
    max_value=600,
    value=200
)

fbs = st.selectbox(
    "Fasting Blood Sugar > 120 mg/dl",
    [0, 1],
    format_func=lambda x: "No" if x == 0 else "Yes"
)

ekg = st.selectbox(
    "EKG Results",
    [0, 1, 2]
)

max_hr = st.number_input(
    "Maximum Heart Rate",
    min_value=50,
    max_value=250,
    value=150
)

exercise_angina = st.selectbox(
    "Exercise-Induced Angina",
    [0, 1],
    format_func=lambda x: "No" if x == 0 else "Yes"
)

st_depression = st.number_input(
    "ST Depression",
    min_value=0.0,
    max_value=10.0,
    value=1.0,
    step=0.1
)

slope = st.selectbox(
    "Slope of ST",
    [1, 2, 3]
)

vessels = st.selectbox(
    "Number of Major Vessels",
    [0, 1, 2, 3]
)

thallium = st.selectbox(
    "Thallium",
    [3, 6, 7]
)

# ================================
# PREDICTION
# ================================

st.divider()

if st.button(
    "🔍 Assess Heart Disease Risk",
    use_container_width=True
):

    input_data = pd.DataFrame([{
        "Age": age,
        "Sex": sex,
        "Chest pain type": chest_pain,
        "BP": bp,
        "Cholesterol": cholesterol,
        "FBS over 120": fbs,
        "EKG results": ekg,
        "Max HR": max_hr,
        "Exercise angina": exercise_angina,
        "ST depression": st_depression,
        "Slope of ST": slope,
        "Number of vessels fluro": vessels,
        "Thallium": thallium
    }])

    prediction = model.predict(input_data)[0]

    st.header("CardioAI Risk Assessment")

    if prediction == "Presence":
        st.error(
            "The model predicts the presence of heart disease."
        )
    else:
        st.success(
            "The model predicts the absence of heart disease."
        )

    st.caption(
        "This prediction is generated by a machine learning model "
        "and should not be interpreted as a clinical diagnosis."
    )
